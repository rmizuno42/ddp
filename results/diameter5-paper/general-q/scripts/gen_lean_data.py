"""Generate the Lean data and check files from the JSON data in ../data.

For every chart, the controllability matrix M_w of each reduced word w is
computed exactly as in DDPGeneralQ/Codes.lean (columns A_t5 A_t4 A_t3 A_t2 b_t1,
..., b_t5; words indexed by t1 + 4 t2 + 16 t3 + 64 t4 + 256 t5), and a
certificate is attached:

* charts over ZMod p, GF(4), GF(8): the inverse N_w with M_w N_w = I;
* integer charts: the determinant d_w and the adjugate adj_w, M_w adj_w = d_w I.

Each certificate is re-checked here before it is written. The Lean side checks
it again with `decide +kernel`.

Usage: python3 gen_lean_data.py   (writes ../lean/DDPGeneralQ/Data/*.lean and
                                    ../lean/DDPGeneralQ/Charts/*.lean)
"""
import json
import sys
sys.set_int_max_str_digits(1000000)
import math
import os
from itertools import product

from gfq import GF

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, os.pardir, 'data')
LEAN = os.path.join(HERE, os.pardir, 'lean', 'DDPGeneralQ')
INV = [1, 0, 3, 2]
SMALL_PRIMES = [p for p in range(3, 80) if all(p % d for d in range(2, p))]
WORDS = [w for w in product(range(4), repeat=5) if all(w[i + 1] != INV[w[i]] for i in range(4))]
assert len(WORDS) == 324


def code(w):
    return sum(t * 4 ** i for i, t in enumerate(w))


# ---------- generic matrix arithmetic over a "field-like" object ----------

class Ring:
    def __init__(self, add, mul, zero, one):
        self.add, self.mul, self.zero, self.one = add, mul, zero, one

    def dot(self, r, v):
        s = self.zero
        for x, y in zip(reversed(r), reversed(v)):   # same nesting as the Lean `dot`
            s = self.add(self.mul(x, y), s)
        return s

    def mv(self, M, v):
        return [self.dot(row, v) for row in M]

    def mm(self, M, N):
        return [[self.dot(row, [N[k][j] for k in range(5)]) for j in range(5)] for row in M]


def ctrl(R, A, b, w):
    t1, t2, t3, t4, t5 = w
    mv = R.mv
    cols = [mv(A[t5], mv(A[t4], mv(A[t3], mv(A[t2], b[t1])))),
            mv(A[t5], mv(A[t4], mv(A[t3], b[t2]))),
            mv(A[t5], mv(A[t4], b[t3])),
            mv(A[t5], b[t4]),
            b[t5]]
    return [[cols[j][i] for j in range(5)] for i in range(5)]


def diag(R, d):
    return [[d if i == j else R.zero for j in range(5)] for i in range(5)]


def check_chart_codes(R, A, b):
    for t in range(4):
        assert R.mm(A[INV[t]], A[t]) == diag(R, R.one), f'A_inv fails at {t}'
        assert b[INV[t]] == R.mv(A[INV[t]], b[t]), f'b_inv fails at {t}'


def inverse_field(F, M):
    """Inverse over gfq.GF (tables) of a 5x5 matrix, or None."""
    return F.inverse(M)


# ---------- integer determinants and adjugates ----------

def det_int(M):
    """Exact determinant (Bareiss)."""
    A = [list(r) for r in M]
    n, sign, prev = len(A), 1, 1
    for k in range(n - 1):
        if A[k][k] == 0:
            sw = next((i for i in range(k + 1, n) if A[i][k] != 0), None)
            if sw is None:
                return 0
            A[k], A[sw] = A[sw], A[k]
            sign = -sign
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                A[i][j] = (A[i][j] * A[k][k] - A[i][k] * A[k][j]) // prev
        prev = A[k][k]
    return sign * A[n - 1][n - 1]


def adjugate_int(M):
    n = len(M)
    adj = [[0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            minor = [row[:j] + row[j + 1:] for k, row in enumerate(M) if k != i]
            adj[j][i] = (-1) ** (i + j) * det_int(minor)
    return adj


# ---------- Lean output ----------

def lst(x):
    if isinstance(x, list):
        return '[' + ', '.join(lst(y) for y in x) + ']'
    return str(x)


HEADER = '/- Generated by general-q/scripts/gen_lean_data.py from general-q/data. Do not edit. -/\n'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)


def cert_list_field(F_ring, inverse, A, b):
    certs = [[] for _ in range(1024)]
    for w in WORDS:
        M = ctrl(F_ring, A, b, w)
        N = inverse(M)
        assert N is not None, f'singular controllability matrix for {w}'
        assert F_ring.mm(M, N) == diag(F_ring, F_ring.one)
        certs[code(w)] = N
    return certs


def gen_zmod(p):
    chart = json.load(open(os.path.join(DATA, 'charts', f'gf{p}.json')))
    assert chart['q'] == p
    A, b = chart['A'], chart['b']
    R = Ring(lambda x, y: (x + y) % p, lambda x, y: (x * y) % p, 0, 1 % p)
    check_chart_codes(R, A, b)
    F = GF(p)
    certs = cert_list_field(R, F.inverse, A, b)
    name = f'ZMod{p}'
    write(os.path.join(LEAN, 'Charts', f'{name}.lean'), HEADER + f'''import DDPGeneralQ.Instances

/-! Universal chart over `ZMod {p}` (`data/charts/gf{p}.json`) with inverse certificates. -/

namespace DDP.{name}

set_option maxRecDepth 100000

def chart : CodeChart ℕ := ⟨{lst(A)}, {lst(b)}⟩

def certs : List (List (List ℕ)) :=
  {lst(certs)}

theorem check : chart.checkB (natModOps {p}) = true := by decide +kernel

theorem univ : chart.univB (natModOps {p}) certs = true := by decide +kernel

end DDP.{name}

namespace DDP

theorem good_{p} : Good {p} := good_of_natMod {p} {name}.chart {name}.certs {name}.check {name}.univ

end DDP
''')
    return name


def gen_gf(q):
    chart = json.load(open(os.path.join(DATA, 'charts', f'gf{q}.json')))
    assert chart['q'] == q
    A, b = chart['A'], chart['b']
    F = GF(q)
    R = Ring(lambda x, y: F.add[x][y], lambda x, y: F.mul[x][y], 0, 1)
    check_chart_codes(R, A, b)
    certs = cert_list_field(R, F.inverse, A, b)
    name = f'GF{q}Chart'
    ops = f'GF{q}.ops'
    good = {4: 'good_four', 8: 'good_eight'}[q]
    write(os.path.join(LEAN, 'Charts', f'{name}.lean'), HEADER + f'''import DDPGeneralQ.Instances

/-! Universal chart over GF({q}) (`data/charts/gf{q}.json`) with inverse certificates. -/

namespace DDP.{name}

set_option maxRecDepth 100000

def chart : CodeChart ℕ := ⟨{lst(A)}, {lst(b)}⟩

def certs : List (List (List ℕ)) :=
  {lst(certs)}

theorem check : chart.checkB {ops} = true := by decide +kernel

theorem univ : chart.univB {ops} certs = true := by decide +kernel

end DDP.{name}

namespace DDP

theorem good_{q} : Good {q} := {good} {name}.chart {name}.certs {name}.check {name}.univ

end DDP
''')
    return name


def gen_int():
    data = json.load(open(os.path.join(DATA, 'charts', 'integer_charts.json')))
    R = Ring(lambda x, y: x + y, lambda x, y: x * y, 0, 1)
    prods = []
    names = []
    for i, ch in enumerate(data['charts'], 1):
        A, b = ch['A'], ch['b']
        check_chart_codes(R, A, b)
        dets = [1] * 1024
        adjs = [[] for _ in range(1024)]
        for w in WORDS:
            M = ctrl(R, A, b, w)
            d = det_int(M)
            adj = adjugate_int(M)
            assert d != 0 and R.mm(M, adj) == diag(R, d)
            dets[code(w)] = d
            adjs[code(w)] = adj
        prods.append(math.prod(abs(d) for d in dets))
        name = f'IntChart{i}'
        names.append(name)
        write(os.path.join(LEAN, 'Charts', f'{name}.lean'), HEADER + f'''import DDPGeneralQ.Instances

/-! Integer chart {i} (`data/charts/integer_charts.json`) with determinant and adjugate
certificates. -/

namespace DDP.{name}

set_option maxRecDepth 100000

def chart : CodeChart ℤ := ⟨{lst(A)}, {lst(b)}⟩

def dets : List ℤ :=
  {lst(dets)}

def adjs : List (List (List ℤ)) :=
  {lst(adjs)}

theorem check : chart.checkB intOps = true := by decide +kernel

theorem adj : chart.adjB intOps dets adjs = true := by decide +kernel

theorem dets_length : dets.length = 1024 := by decide +kernel

end DDP.{name}
''')
    g = 0
    for P in prods:
        g = math.gcd(g, P)
    fac = []
    r = g
    for q in range(2, 1000):
        if all(q % d for d in range(2, q)):
            e = 0
            while r % q == 0:
                r //= q
                e += 1
            if e:
                fac.append((q, e))
    assert r == 1, 'gcd has a large prime factor'
    assert max(q for q, _ in fac) <= 79
    return names, fac


def gen_controller():
    c = json.load(open(os.path.join(DATA, 'controller.json')))
    n = c['vertices']
    assert n < 256
    sig = [sum(c['sigma'][t][u] << (8 * u) for u in range(n)) for t in range(4)]
    cert = sum(c['certificates'][u][v] << (10 * (n * u + v)) for u in range(n) for v in range(n))
    assert all(0 <= c['certificates'][u][v] < 1024 for u in range(n) for v in range(n))
    write(os.path.join(LEAN, 'Charts', 'Controller.lean'), HEADER + f'''import DDPGeneralQ.Checks

/-! The 144-vertex controller of arXiv:2606.15860 (`data/controller.json`).

The arc tables and the certificate words are packed into natural numbers with
fixed-width fields, so that a lookup is one shift and one remainder: the head
of the arc with symbol `t` leaving `u` is the 8-bit field `u` of `sigmaNat t`,
and the code of the reduced word from `u` to `v` is the 10-bit field
`{n} u + v` of `certNat`. -/

namespace DDP.Ctrl

def sigmaNat : Sym → ℕ := ![{sig[0]},
  {sig[1]},
  {sig[2]},
  {sig[3]}]

def certNat : ℕ :=
  {cert}

/-- The head of the arc with symbol `t` leaving `u`. -/
def σ (t : Sym) (u : Fin {n}) : Fin {n} :=
  ⟨((sigmaNat t >>> (8 * u.val)) % 256) % {n}, Nat.mod_lt _ (by norm_num)⟩

/-- The code of the certified reduced word from `u` to `v`. -/
def cert (u v : ℕ) : ℕ := (certNat >>> (10 * ({n} * u + v))) % 1024

theorem σ_inv : ∀ t u, σ (inv t) (σ t u) = u := by decide +kernel

def controller : Controller (Fin {n}) := ⟨σ, σ_inv⟩

theorem cert_ok : ctrlB controller.σ cert = true := by decide +kernel

theorem exactNB5 : controller.ExactNB5 := exactNB5_of_ctrlB controller cert_ok

end DDP.Ctrl
''')


def main():
    import sys
    only = sys.argv[1:]
    if not only or 'controller' in only:
        gen_controller()
    zmods = []
    for p in SMALL_PRIMES:
        if not only or f'zmod{p}' in only or 'zmod' in only:
            zmods.append(gen_zmod(p))
    for q in (4, 8):
        if not only or f'gf{q}' in only:
            gen_gf(q)
    if not only or 'int' in only:
        names, fac = gen_int()
        json.dump({'integer_chart_modules': names, 'gcd_factorization': fac},
                  open(os.path.join(HERE, 'int_gcd.json'), 'w'))
        print('gcd factorization:', fac)
    print('generated:', zmods)


if __name__ == '__main__':
    main()
